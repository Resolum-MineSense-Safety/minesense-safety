#!/usr/bin/env bash
# Writes infrastructure/gitops/environments/<env>/platform/*.yaml from the Terraform outputs of an
# environment (section 4.2): the same per-service settings that deploy.sh passes with --set, as
# values files that Argo CD reads from Git. None of them is a secret (ARNs, URLs, broker list);
# credentials stay in AWS Secrets Manager and Kubernetes Secrets.
#
#   infrastructure/scripts/gitops-platform-values.sh staging   # then commit the files in a PR
set -euo pipefail
source "$(dirname "$0")/lib/common.sh"

ENVIRONMENT="${1:?usage: gitops-platform-values.sh <staging|production>}"
require_environment "$ENVIRONMENT"
require_tools terraform
STACK="$(stack_dir "$ENVIRONMENT")"
OUT="$REPO_ROOT/infrastructure/gitops/environments/$ENVIRONMENT/platform"
mkdir -p "$OUT"

kafka="$(tf_output "$STACK" kafka_bootstrap_brokers || true)"
kafka_role="$(tf_output "$STACK" kafka_client_role_arn || true)"
reporting_role="$(tf_output "$STACK" reporting_service_role_arn || true)"
queue="$(tf_output "$STACK" report_requests_queue_url || true)"
bucket="$(tf_output "$STACK" reports_bucket || true)"

header="# Generated by infrastructure/scripts/gitops-platform-values.sh from the Terraform outputs of $ENVIRONMENT."
# Services that publish or consume domain events (same list as deploy.sh).
for service in alert-service analytics-service edge-synchronization-service fatigue-detection-service \
  feedback-reliability-service fleet-monitoring-service incident-management-service privacy-audit-service; do
  printf '%s\nenv:\n  Kafka__BootstrapServers: "%s"\nserviceAccount:\n  roleArn: "%s"\n' \
    "$header" "$kafka" "$kafka_role" >"$OUT/$service.yaml"
done
printf '%s\nenv:\n  Kafka__BootstrapServers: "%s"\n  Reporting__SqsQueueUrl: "%s"\n  Reporting__S3Bucket: "%s"\nserviceAccount:\n  roleArn: "%s"\n' \
  "$header" "$kafka" "$queue" "$bucket" "$reporting_role" >"$OUT/reporting-service.yaml"
printf '%s\nhost: "%s"\ncertificateArn: "%s"\n' "$header" "${API_HOST:-}" "${ACM_CERTIFICATE_ARN:-}" >"$OUT/minesense-gateway.yaml"
ls "$OUT"
