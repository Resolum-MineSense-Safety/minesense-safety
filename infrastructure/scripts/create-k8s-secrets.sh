#!/usr/bin/env bash
# Creates or updates the Kubernetes Secrets of one environment from the Terraform outputs and AWS
# Secrets Manager. Idempotent and silent about values: secrets travel through pipes (never through
# command-line arguments) and only their names are printed.
#
#   infrastructure/scripts/create-k8s-secrets.sh <staging|production>
#
# Needs AWS credentials, kubectl pointing at the cluster and the Terraform stack initialized.
# Optional: GHCR_TOKEN and GHCR_USERNAME create the image pull secret "ghcr-pull".
#
# Secret                         Keys
# identity-access-secrets        JWT signing key, bootstrap administrator, PostgreSQL minesense_identity
# operations-secrets             PostgreSQL minesense_operations
# device-management-secrets      PostgreSQL minesense_devices
# monitoring-secrets             PostgreSQL minesense_monitoring
# <document context>-secrets     DocumentDB (each service picks its database with MongoDb__Database)
# minesense-demo-credentials     Password of the demo users of seed-demo.mjs
set -euo pipefail
source "$(dirname "$0")/lib/common.sh"

ENVIRONMENT="${1:?usage: create-k8s-secrets.sh <staging|production>}"
require_environment "$ENVIRONMENT"
require_tools aws terraform kubectl openssl curl
STACK="$(stack_dir "$ENVIRONMENT")"
BUNDLE_URL="https://truststore.pki.rds.amazonaws.com/global/global-bundle.pem"

# Name of the Deployment that loads each secret (restarted when the secret changes).
deployment_of() { printf '%s-service' "${1%-secrets}"; }

# apply_secret <name> <type> KEY VALUE [KEY VALUE...]
apply_secret() {
  local name="$1" type="$2" result deployment
  shift 2
  result="$({
    printf 'apiVersion: v1\nkind: Secret\nmetadata:\n  name: %s\n  namespace: %s\n  labels:\n    app.kubernetes.io/part-of: minesense-safety\ntype: %s\ndata:\n' \
      "$name" "$ENVIRONMENT" "$type"
    while (($# > 0)); do
      printf '  %s: %s\n' "$1" "$(printf '%s' "$2" | b64)"
      shift 2
    done
  } | kubectl apply -f - | tr -d '\r')"
  printf '  %s\n' "$result"
  # envFrom is read when the pod starts: a changed secret (e.g. a rotated password) needs a restart.
  if [[ "$result" == *configured* ]]; then
    deployment="$(deployment_of "$name")"
    kubectl rollout restart "deployment/$deployment" -n "$ENVIRONMENT" 2>/dev/null || true
  fi
}

log "Namespace y CA de Amazon DocumentDB"
kubectl apply -f "$REPO_ROOT/infrastructure/k8s/namespaces.yaml" >/dev/null
bundle_dir="$(mktemp -d)"
# E:/... form on Windows, valid for bash and for the native curl and kubectl.
if command -v cygpath >/dev/null 2>&1; then bundle_dir="$(cygpath -m "$bundle_dir")"; fi
trap 'rm -rf "$bundle_dir"' EXIT
curl -fsSL --retry 3 "$BUNDLE_URL" -o "$bundle_dir/global-bundle.pem"
# Server-side apply: at ~175 KB the bundle would not fit in the last-applied annotation.
kubectl create configmap documentdb-ca -n "$ENVIRONMENT" --from-file="global-bundle.pem=$bundle_dir/global-bundle.pem" \
  --dry-run=client -o yaml | kubectl apply --server-side --force-conflicts -f - >/dev/null
echo "  configmap/documentdb-ca"

log "Secretos de PostgreSQL y DocumentDB"
pg_host="$(tf_output "$STACK" postgres_address)"
pg_secret_arn="$(tf_output "$STACK" postgres_secret_arn)"
doc_host="$(tf_output "$STACK" documentdb_endpoint)"
doc_secret_arn="$(tf_output "$STACK" documentdb_secret_arn)"
[[ -n "$pg_host" && -n "$pg_secret_arn" && -n "$doc_host" && -n "$doc_secret_arn" ]] ||
  die "Faltan salidas de Terraform en $STACK: ejecuta primero terraform apply."

pg_json="$(aws secretsmanager get-secret-value --secret-id "$pg_secret_arn" --query SecretString --output text | tr -d '\r')"
pg_user="$(printf '%s' "$pg_json" | json_field username)"
pg_password="$(printf '%s' "$pg_json" | json_field password)"
doc_json="$(aws secretsmanager get-secret-value --secret-id "$doc_secret_arn" --query SecretString --output text | tr -d '\r')"
doc_user="$(printf '%s' "$doc_json" | json_field username)"
doc_password="$(printf '%s' "$doc_json" | json_field password)"
unset pg_json doc_json
[[ -n "$pg_user" && -n "$pg_password" && -n "$doc_user" && -n "$doc_password" ]] ||
  die "No se pudieron leer las credenciales de Secrets Manager."

# The password generated by RDS may contain ; or =, so it goes quoted (a ' is doubled).
pg_quoted="'${pg_password//\'/\'\'}'"
# rds.force_ssl is on by default in PostgreSQL 16 on RDS.
postgres_connection() {
  printf "Host=%s;Port=5432;Database=%s;Username=%s;Password=%s;SSL Mode=Require" "$pg_host" "$1" "$pg_user" "$pg_quoted"
}

# DocumentDB: TLS required, a single writer endpoint and no retryable writes on engine 5.0. The
# generated password is alphanumeric, so it needs no URL encoding. Reads go to the primary so a
# service reads its own writes.
mongo_connection="mongodb://$doc_user:$doc_password@$doc_host:27017/?tls=true&replicaSet=rs0&readPreference=primary&retryWrites=false&authMechanism=SCRAM-SHA-1"

for context in alert analytics edge-synchronization fatigue-detection feedback-reliability \
  fleet-monitoring incident-management privacy-audit reporting; do
  apply_secret "$context-secrets" Opaque ConnectionStrings__MongoDb "$mongo_connection"
done
apply_secret operations-secrets Opaque ConnectionStrings__PostgreSql "$(postgres_connection minesense_operations)"
apply_secret device-management-secrets Opaque ConnectionStrings__PostgreSql "$(postgres_connection minesense_devices)"
apply_secret monitoring-secrets Opaque ConnectionStrings__PostgreSql "$(postgres_connection minesense_monitoring)"

log "Identity & Access (la clave y el administrador se generan una sola vez)"
jwt_key="$(read_secret_key "$ENVIRONMENT" identity-access-secrets IdentityAccess__Jwt__PrivateKeyPem || true)"
[[ -n "$jwt_key" ]] || jwt_key="$(openssl genrsa 2048 2>/dev/null | tr -d '\r')"
admin_password="$(read_secret_key "$ENVIRONMENT" identity-access-secrets IdentityAccess__BootstrapAdministrator__Password || true)"
[[ -n "$admin_password" ]] || admin_password="$(random_password)"
apply_secret identity-access-secrets Opaque \
  IdentityAccess__Jwt__PrivateKeyPem "$jwt_key" \
  IdentityAccess__BootstrapAdministrator__Username admin \
  IdentityAccess__BootstrapAdministrator__Password "$admin_password" \
  ConnectionStrings__PostgreSql "$(postgres_connection minesense_identity)"

demo_password="$(read_secret_key "$ENVIRONMENT" minesense-demo-credentials DEMO_PASSWORD || true)"
[[ -n "$demo_password" ]] || demo_password="$(random_password)"
apply_secret minesense-demo-credentials Opaque DEMO_PASSWORD "$demo_password"

# ---------- Private GHCR packages ----------
if [[ -n "${GHCR_TOKEN:-}" ]]; then
  log "Credencial de GHCR para descargar imágenes"
  ghcr_user="${GHCR_USERNAME:-minesense}"
  ghcr_auth="$(printf '%s:%s' "$ghcr_user" "$GHCR_TOKEN" | b64)"
  apply_secret ghcr-pull kubernetes.io/dockerconfigjson .dockerconfigjson \
    "{\"auths\":{\"ghcr.io\":{\"username\":\"$ghcr_user\",\"auth\":\"$ghcr_auth\"}}}"
fi

echo
echo "Secretos listos en el namespace $ENVIRONMENT. Para leer la clave del administrador:"
echo "  kubectl get secret identity-access-secrets -n $ENVIRONMENT -o jsonpath='{.data.IdentityAccess__BootstrapAdministrator__Password}' | base64 -d"
