#!/usr/bin/env python3
"""Renders the nginx configuration of the local API gateway (docker-compose) from the routes of
the Helm chart minesense-gateway, so the local entry point and the cloud ALB route /api/v1 the
same way (section 3.1). Run it after changing infrastructure/helm/minesense-gateway/values.yaml:

    python infrastructure/scripts/render-gateway-nginx.py

The CI fails if the committed file differs from the rendered one.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
VALUES = ROOT / "infrastructure" / "helm" / "minesense-gateway" / "values.yaml"
OUTPUT = ROOT / "infrastructure" / "docker" / "gateway" / "nginx.conf"
SERVICE_PORT = 8080


def read_routes():
    """Reads the ordered (path, service) pairs under `routes:` without a YAML dependency."""
    routes, path = [], None
    in_routes = False
    for line in VALUES.read_text(encoding="utf-8").splitlines():
        if line.startswith("routes:"):
            in_routes = True
            continue
        if not in_routes:
            continue
        if line and not line.startswith((" ", "#")):
            break
        match = re.match(r"\s*-\s*path:\s*(\S+)", line)
        if match:
            path = match.group(1)
            continue
        match = re.match(r"\s*service:\s*(\S+)", line)
        if match and path:
            routes.append((path, match.group(1)))
            path = None
    return routes


def location_blocks(path, service):
    target = f"        set $upstream {service};\n        proxy_pass http://$upstream:{SERVICE_PORT};\n"
    if "*" in path:
        # ALB wildcard: "*" stands for one path segment. Regex locations win over prefixes.
        regex = "^" + re.escape(path).replace(r"\*", "[^/]+") + "(/.*)?$"
        return [f"    location ~ {regex} {{\n{target}    }}\n"]
    # ALB Prefix semantics: the path itself and everything under it, segment by segment.
    return [
        f"    location = {path} {{\n{target}    }}\n",
        f"    location {path.rstrip('/')}/ {{\n{target}    }}\n",
    ]


def render():
    routes = read_routes()
    wildcard = [r for r in routes if "*" in r[0]]
    prefix = [r for r in routes if "*" not in r[0]]
    blocks = [b for p, s in wildcard + prefix for b in location_blocks(p, s)]
    return (
        "# GENERATED by infrastructure/scripts/render-gateway-nginx.py from\n"
        "# infrastructure/helm/minesense-gateway/values.yaml. Do not edit by hand.\n"
        "# Local equivalent of the ALB Ingress: single entry point /api/v1 plus the dashboard.\n"
        "server {\n"
        "    listen 8080;\n"
        "    server_name _;\n"
        "    server_tokens off;\n"
        "    client_max_body_size 10m;\n"
        "\n"
        "    # Docker DNS; resolving at request time lets the gateway start before the services.\n"
        "    resolver 127.0.0.11 valid=10s ipv6=off;\n"
        "\n"
        "    proxy_http_version 1.1;\n"
        "    proxy_set_header Host $host;\n"
        "    proxy_set_header X-Real-IP $remote_addr;\n"
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
        "    proxy_set_header X-Forwarded-Proto $scheme;\n"
        "    proxy_set_header Authorization $http_authorization;\n"
        "\n"
        "    location = /healthz {\n"
        "        access_log off;\n"
        "        default_type text/plain;\n"
        "        return 200 \"ok\";\n"
        "    }\n"
        "\n"
        + "\n".join(blocks)
        + "\n"
        "    location /api/ {\n"
        "        default_type application/json;\n"
        "        return 404 '{\"message\":\"No microservice serves this route.\"}';\n"
        "    }\n"
        "\n"
        "    location / {\n"
        "        set $upstream supervision-dashboard;\n"
        f"        proxy_pass http://$upstream:{SERVICE_PORT};\n"
        "    }\n"
        "}\n"
    )


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
